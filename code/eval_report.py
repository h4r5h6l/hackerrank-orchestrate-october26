#!/usr/bin/env python3
"""Evaluation report stub for the Ghost Data Still Exists submission.

Stage 0 stub: it inspects the current ``output.csv`` and the public sample
answers and prints the scaffolding for the report required by AGENTS.md
section 6.8. It deliberately computes no accuracy numbers yet.

Planned metrics (all currently TODO):
  * case-level deletion-status accuracy  (output vs sample_output.csv)
  * step-level / field-level accuracy    (operation, state, system_id,
                                          resource_id, evidence_id)
  * sequence accuracy                    (phase block order + step_no)
  * participant-authored evaluation cases (>= 3, kept in tests/cases.py)

Usage:
    python3 code/eval_report.py
    python3 code/eval_report.py --sample /tmp/sample_run.csv
    python3 code/eval_report.py --write /tmp/evaluation_report.md

Notes:
  * ``--write`` targets an explicit path; without it nothing is written, so the
    checked-in reports under ``code/evaluation/`` are never clobbered by a stub.
  * The public sample answers cover case_01..case_32 only; they do not contain
    a single NOT_APPLICABLE row, so that status has no sample coverage.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from collections import Counter
from typing import Sequence

CODE_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(CODE_DIR)
DEFAULT_OUTPUT = os.path.join(REPO_ROOT, "output.csv")
DEFAULT_SAMPLE = os.path.join(REPO_ROOT, "dataset", "sample_output.csv")

STATUSES = ("COMPLETE", "INCOMPLETE", "NOT_APPLICABLE")
PHASES = ("FINDING", "REMEDIATION", "VERIFICATION")

REPORT_TODO = """\
# Evaluation Report (STUB)

> Generated by `code/eval_report.py`, stage 0 skeleton.
> **Numbers are not computed yet.** Do not submit this file as-is.

## Case-level deletion-status accuracy
TODO: compare `deletion_status` per `case_id` against `dataset/sample_output.csv`.

## Step-level and field-level accuracy
TODO: compare step counts, then per-field agreement on
`operation`, `state`, `system_id`, `resource_id`, `evidence_id`.

## Sequence accuracy
TODO: verify phase block order (FINDING -> REMEDIATION -> VERIFICATION),
contiguous `step_no` from 1, and within-phase ordering.

## Participant-created evaluation cases
TODO: at least three hand-written cases with expected steps.

## Failures found and improvements made
TODO: populate from real runs.
"""


def load_csv(path: str) -> list[dict]:
    with open(path, newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def load_steps(row: dict) -> list[dict]:
    try:
        steps = json.loads(row.get("steps_json") or "[]")
    except json.JSONDecodeError:
        return []
    return steps if isinstance(steps, list) else []


def describe(path: str, label: str) -> dict:
    """Structural summary only - no accuracy scoring in stage 0."""
    rows = load_csv(path)
    statuses = Counter(row.get("deletion_status", "") for row in rows)
    steps = [s for row in rows for s in load_steps(row)]
    phases = Counter(s.get("phase", "") for s in steps)
    return {
        "label": label,
        "path": path,
        "rows": len(rows),
        "statuses": {s: statuses.get(s, 0) for s in STATUSES},
        "steps": len(steps),
        "phases": {p: phases.get(p, 0) for p in PHASES},
        "with_evidence": sum(1 for s in steps if s.get("evidence_id")),
    }


def compute_report(output_path: str, sample_path: str) -> dict:
    """TODO(stage 4): return real accuracy metrics instead of this scaffolding."""
    return {
        "output": describe(output_path, "current output.csv"),
        "sample": describe(sample_path, "public sample answers"),
        "metrics": {
            "case_status_accuracy": None,
            "step_field_accuracy": None,
            "sequence_accuracy": None,
            "custom_cases": None,
        },
    }


def render_markdown(report: dict) -> str:
    out = report["output"]
    sample = report["sample"]
    lines = [
        REPORT_TODO.rstrip(),
        "",
        "## Observed shapes (informational only)",
        "",
        f"- current output: {out['rows']} rows, {out['steps']} steps, "
        f"statuses {out['statuses']}",
        f"- public sample: {sample['rows']} rows, {sample['steps']} steps, "
        f"statuses {sample['statuses']}",
        f"- sample phase mix: {sample['phases']}",
        f"- sample steps citing evidence: {sample['with_evidence']}/{sample['steps']}",
    ]
    return "\n".join(lines) + "\n"


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="eval_report.py",
        description="Evaluation report stub (stage 0): structure only, no scoring.",
    )
    parser.add_argument("--output", default=DEFAULT_OUTPUT,
                        help="candidate output CSV (default: <repo>/output.csv)")
    parser.add_argument("--sample", default=DEFAULT_SAMPLE,
                        help="public sample answers (default: dataset/sample_output.csv)")
    parser.add_argument("--write", metavar="PATH", default=None,
                        help="write the stub markdown to PATH (never the checked-in report)")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    for path in (args.output, args.sample):
        if not os.path.isfile(path):
            print(f"error: file not found: {path}", file=sys.stderr)
            return 1

    report = compute_report(args.output, args.sample)
    out = report["output"]
    print(f"[stub] {out['label']}: {out['rows']} rows, {out['steps']} steps, "
          f"statuses {out['statuses']}")
    print(f"[stub] metrics not implemented: {report['metrics']}")
    print("[stub] TODO: status accuracy, step/field accuracy, sequence accuracy, "
          "3+ custom cases")

    if args.write:
        with open(args.write, "w", encoding="utf-8") as handle:
            handle.write(render_markdown(report))
        print(f"[stub] wrote stub report -> {args.write}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
